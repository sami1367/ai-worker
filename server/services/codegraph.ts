import { chmod, mkdir, rename, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { asc, isNotNull } from 'drizzle-orm'
import { users } from '#db/schema'
import { getDb } from '#utils/db'
import { workerBaseDir } from '#utils/paths'

function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`
}

/**
 * Write CodeGraph-related env for the Bash worker (email for waitlist signup).
 * File is sourced by worker-entrypoint / platform-wrapper.
 */
export async function exportCodegraphEnv(email?: string | null): Promise<{
  path: string
  email: string | null
}> {
  let resolved = (email || '').trim().toLowerCase() || null
  if (!resolved) {
    const db = getDb()
    const [row] = await db
      .select({ email: users.email })
      .from(users)
      .where(isNotNull(users.email))
      .orderBy(asc(users.createdAt))
      .limit(1)
    resolved = row?.email?.trim().toLowerCase() || null
  }

  const base = workerBaseDir()
  await mkdir(base, { recursive: true })
  const target = join(base, 'codegraph.env')
  const tmp = `${target}.${process.pid}.${Date.now()}.tmp`
  const lines = [
    '# Generated by AI Worker Platform — do not edit. Mode 0600.',
    '# Used by the worker to configure CodeGraph (agent MCP + waitlist email).',
    resolved
      ? `export CODEGRAPH_EMAIL=${shellQuote(resolved)}`
      : 'export CODEGRAPH_EMAIL=',
    '',
  ]
  await writeFile(tmp, lines.join('\n'), { mode: 0o600 })
  await chmod(tmp, 0o600)
  await rename(tmp, target)
  await chmod(target, 0o600)
  return { path: target, email: resolved }
}
