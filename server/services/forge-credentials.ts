import { chmod, mkdir, rename, writeFile, unlink } from 'node:fs/promises'
import { join } from 'node:path'
import { and, eq } from 'drizzle-orm'
import { forgeConnections, repositories } from '#db/schema'
import { getDb } from '#utils/db'
import { decryptSecret } from '#utils/crypto'
import { workerBaseDir } from '#utils/paths'
import { GITHUB_INSTANCE_URL } from './forge-github'

/**
 * Materialize forge tokens for the Bash worker into a 0600 env file on the
 * shared config volume. Tokens are never written into project conf JSON.
 *
 * Single global GH_TOKEN / GITLAB_TOKEN model:
 * - Prefer the connection used by enabled repositories (instance URL match)
 * - Else fall back to the most recently validated active connection
 */
export async function exportForgeCredentialsForWorker(): Promise<{
  path: string
  github: boolean
  gitlab: boolean
}> {
  const db = getDb()
  const rows = await db.select().from(forgeConnections).where(eq(forgeConnections.status, 'active'))
  const key = process.env.SECRET_ENCRYPTION_KEY || ''

  let githubToken = process.env.GITHUB_TOKEN || process.env.GH_TOKEN || ''
  let gitlabToken = process.env.GITLAB_TOKEN || ''
  let gitlabHost = process.env.GITLAB_HOST || ''

  const enabledRepos = await db.select({
    forgeType: repositories.forgeType,
    connectionId: repositories.connectionId,
    instanceUrl: repositories.instanceUrl,
  }).from(repositories).where(and(
    eq(repositories.isEnabled, true),
    eq(repositories.isArchived, false),
  ))

  const pickConnection = (provider: 'github' | 'gitlab') => {
    const candidates = rows.filter((r) => r.provider === provider && r.accessTokenCiphertext)
    if (!candidates.length) return undefined

    const enabledForProvider = enabledRepos.filter((r) => r.forgeType === provider)
    // Prefer connection id used by enabled repos
    for (const repo of enabledForProvider) {
      if (!repo.connectionId) continue
      const match = candidates.find((c) => c.id === repo.connectionId)
      if (match) return match
    }
    // Prefer instance URL used by enabled repos
    for (const repo of enabledForProvider) {
      if (!repo.instanceUrl) continue
      const match = candidates.find((c) => c.instanceUrl === repo.instanceUrl)
      if (match) return match
    }
    return candidates.sort((a, b) => (b.lastValidatedAt?.getTime() || 0) - (a.lastValidatedAt?.getTime() || 0))[0]
  }

  const github = pickConnection('github')
  const gitlab = pickConnection('gitlab')

  if (github && key) {
    try {
      githubToken = decryptSecret(github.accessTokenCiphertext!, key)
    } catch {
      // Keep env fallback
    }
  }
  if (gitlab && key) {
    try {
      gitlabToken = decryptSecret(gitlab.accessTokenCiphertext!, key)
      try {
        gitlabHost = new URL(gitlab.instanceUrl).host
      } catch {
        gitlabHost = gitlab.instanceUrl.replace(/^https?:\/\//, '')
      }
    } catch {
      // Keep env fallback
    }
  }

  const base = workerBaseDir()
  await mkdir(base, { recursive: true })
  const target = join(base, 'forge-credentials.env')
  const tmp = `${target}.${process.pid}.${Date.now()}.tmp`

  const lines = [
    '# Generated by AI Worker Platform — do not edit. Mode 0600.',
    '# Sourced by the worker entrypoint and each poll cycle. Never commit this file.',
    githubToken ? `export GH_TOKEN=${shellQuote(githubToken)}` : '# GH_TOKEN unset',
    githubToken ? `export GITHUB_TOKEN=${shellQuote(githubToken)}` : '# GITHUB_TOKEN unset',
    gitlabToken ? `export GITLAB_TOKEN=${shellQuote(gitlabToken)}` : '# GITLAB_TOKEN unset',
    gitlabHost ? `export GITLAB_HOST=${shellQuote(gitlabHost)}` : '# GITLAB_HOST unset',
    '',
  ]

  await writeFile(tmp, lines.join('\n'), { mode: 0o600 })
  await chmod(tmp, 0o600)
  await rename(tmp, target)
  await chmod(target, 0o600)

  return {
    path: target,
    github: Boolean(githubToken),
    gitlab: Boolean(gitlabToken),
  }
}

function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`
}

export async function clearForgeCredentialsFile(): Promise<void> {
  try {
    await unlink(join(workerBaseDir(), 'forge-credentials.env'))
  } catch {
    // ignore
  }
}

export function authenticatedCloneUrl(cloneUrl: string, token: string, provider: 'github' | 'gitlab'): string {
  const url = new URL(cloneUrl.replace(/\.git$/, '') + '.git')
  if (provider === 'github') {
    url.username = 'x-access-token'
    url.password = token
  } else {
    url.username = 'oauth2'
    url.password = token
  }
  return url.toString()
}

