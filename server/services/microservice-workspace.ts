import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import { access, mkdir, readdir, rename, rm, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { managedWorkspacePath } from '#utils/paths'
import type { MicroserviceProject } from '#shared/microservices'

const execFileAsync = promisify(execFile)
export function microserviceWorkspacePath(id: string) {
  return managedWorkspacePath(`microservices-${id}`)
}

/** Stable, unique directory names; names and labels never become shell commands. */
export function projectDirectories(projects: Array<{ repositoryId: string, name: string }>) {
  const used = new Set<string>(['.codegraph'])
  return projects.map(project => {
    const base = project.name.split('/').pop()!.toLowerCase().replace(/[^a-z0-9_-]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 60) || 'service'
    let directory = base
    if (used.has(directory)) directory = `${base}-${project.repositoryId}`
    let suffix = 2
    while (used.has(directory)) directory = `${base}-${project.repositoryId}-${suffix++}`
    used.add(directory)
    return directory
  })
}

async function git(args: string[], cwd?: string) {
  const { stdout } = await execFileAsync('git', args, {
    cwd, timeout: 180_000, maxBuffer: 512_000,
    env: { ...process.env, GIT_TERMINAL_PROMPT: '0', GIT_CONFIG_NOSYSTEM: '1' },
  })
  return stdout.trim()
}

/** Clone from an already authenticated, managed source into an independent checkout. */
export async function syncMicroserviceClone(root: string, directory: string, source: string, branch: string) {
  if (!/^[a-z0-9][a-z0-9_-]*$/.test(directory)) throw new Error('Invalid service directory')
  if (!source || !branch || branch.startsWith('-')) throw new Error('Repository source or branch is missing')
  const target = join(root, directory)
  await mkdir(root, { recursive: true })
  let exists = true
  try { await access(join(target, '.git')) } catch { exists = false }
  if (!exists) {
    const temporary = `${target}.clone`
    await rm(temporary, { recursive: true, force: true })
    try {
      await git(['clone', '--no-hardlinks', '--single-branch', '--branch', branch, '--', source, temporary])
      await rename(temporary, target)
    } catch (error) {
      await rm(temporary, { recursive: true, force: true })
      throw error
    }
  }
  // Fetch the configured source branch explicitly, even when the default branch changed.
  await git(['fetch', '--no-tags', '--', source, `refs/heads/${branch}`], target)
  await git(['checkout', '--detach', '--force', 'FETCH_HEAD'], target)
  return git(['rev-parse', 'HEAD'], target)
}

export async function writeMicroserviceManifest(root: string, name: string, description: string, projects: Array<MicroserviceProject & { name: string, commit: string }>) {
  // Only prune directories generated by this feature and tracked in its previous manifest.
  let previous: Array<{ directory: string }> = []
  try {
    const { readFile } = await import('node:fs/promises')
    previous = JSON.parse(await readFile(join(root, 'services.json'), 'utf8')).projects || []
  } catch { /* first preparation */ }
  const current = new Set(projects.map(project => project.directory))
  for (const project of previous) {
    if (/^[a-z0-9][a-z0-9_-]*$/.test(project.directory) && !current.has(project.directory)) {
      await rm(join(root, project.directory), { recursive: true, force: true })
    }
  }
  await writeFile(join(root, 'services.json'), JSON.stringify({ name, description, projects }, null, 2))
  await writeFile(join(root, 'README.md'), [
    `# ${name}`, description, '', '## Services',
    ...projects.map(project => `- ${project.directory}/ — ${project.name}; labels: ${project.labels.join(', ') || 'none'}; ${project.description}; commit: ${project.commit}`),
  ].join('\n'))
}

export async function indexMicroserviceWorkspace(root: string, enabled: boolean) {
  if (!enabled) {
    await rm(join(root, '.codegraph'), { recursive: true, force: true })
    return 'disabled'
  }
  // Rebuild after sync so removed services and changed branches cannot leave stale graph data.
  const initialized = (await readdir(root)).includes('.codegraph')
  await execFileAsync('codegraph', [initialized ? 'index' : 'init', ...(initialized ? [] : ['-y'])], {
    cwd: root, timeout: 300_000, maxBuffer: 512_000,
  })
  return 'ready'
}
