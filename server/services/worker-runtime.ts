import { chmod, mkdir, rename, writeFile, unlink } from 'node:fs/promises'
import { join } from 'node:path'
import { eq } from 'drizzle-orm'
import { providerConfigs } from '#db/schema'
import { getDb } from '#utils/db'
import { workerBaseDir } from '#utils/paths'
import { getSettings } from './settings'
import { wakeWorkerPoll } from './webhooks'

function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`
}

/**
 * Materialize UI settings the Bash worker must honor without a compose recreate:
 * default AI provider, poll interval, and config version.
 */
export async function exportWorkerRuntimeEnv(): Promise<{
  path: string
  aiProvider: string
  checkInterval: number
  configVersion: number
}> {
  const settings = await getSettings()
  const db = getDb()
  const [defaultProvider] = await db.select({
    providerType: providerConfigs.providerType,
  }).from(providerConfigs).where(eq(providerConfigs.isDefault, true)).limit(1)

  const aiProvider = (
    defaultProvider?.providerType === 'cursor'
    || defaultProvider?.providerType === 'claude'
    || defaultProvider?.providerType === 'codex'
    || defaultProvider?.providerType === 'gemini'
  )
    ? defaultProvider.providerType
    : settings.defaultAiProvider

  const checkInterval = settings.pollIntervalSeconds
  const configVersion = settings.configVersion

  const base = workerBaseDir()
  await mkdir(base, { recursive: true })
  const target = join(base, 'worker-runtime.env')
  const tmp = `${target}.${process.pid}.${Date.now()}.tmp`

  const lines = [
    '# Generated by AI Worker Platform — do not edit. Mode 0600.',
    '# Sourced each poll cycle so Settings / Providers UI changes apply quickly.',
    `export AI_PROVIDER=${shellQuote(aiProvider)}`,
    `export CHECK_INTERVAL=${shellQuote(String(checkInterval))}`,
    `export CONFIG_VERSION=${shellQuote(String(configVersion))}`,
    '',
  ]

  await writeFile(tmp, lines.join('\n'), { mode: 0o600 })
  await chmod(tmp, 0o600)
  await rename(tmp, target)
  await chmod(target, 0o600)

  return {
    path: target,
    aiProvider,
    checkInterval,
    configVersion,
  }
}

export async function clearWorkerRuntimeEnvFile(): Promise<void> {
  try {
    await unlink(join(workerBaseDir(), 'worker-runtime.env'))
  } catch {
    // ignore
  }
}

/**
 * After credentials, settings, or repo list change: refresh runtime env and
 * wake the worker poll loop so the next cycle picks changes up in seconds.
 */
export async function applyWorkerRuntimeChange(
  reason: string,
  metadata: Record<string, unknown> = {},
): Promise<void> {
  try {
    await exportWorkerRuntimeEnv()
  } catch (err) {
    console.warn(
      '[worker-runtime] Failed to export runtime env:',
      err instanceof Error ? err.message : err,
    )
  }
  try {
    await wakeWorkerPoll(reason, metadata)
  } catch (err) {
    console.warn(
      '[worker-runtime] Failed to wake worker poll:',
      err instanceof Error ? err.message : err,
    )
  }
}
